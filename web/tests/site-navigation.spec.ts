import { test, expect } from './fixtures'

for (const width of [1920, 375]) {
  test('volet superposé, clavier et sessions stables à ' + width, async ({ page, request }, info) => {
    const video = await (await request.post('/api/v1/videos', { data: { url: 'https://youtu.be/trNav' + String(width).padStart(6, '0') } })).json()
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/videos/' + video.id)
    const editor = page.getByRole('textbox', { name: 'Note Markdown' })
    await editor.fill('Texte conservé')
    const node = await editor.elementHandle()
    await editor.press('Control+a')
    await expect(page.locator('.youtube-frame iframe')).toBeVisible()
    const playerCount = await page.evaluate(() => window.youtubeTest.players.length)
    const geometry = () => page.locator('.video-workspace').evaluate(el => {
      const r = el.getBoundingClientRect()
      return { x: r.x, y: r.y + scrollY, width: r.width, height: r.height }
    })
    const before = await geometry()
    const trigger = page.getByRole('button', { name: 'Ouvrir la navigation', exact: true })
    await trigger.click()
    const dialog = page.getByRole('dialog', { name: 'Navigation', exact: true })
    await expect(dialog).toBeVisible()
    await expect(page.getByRole('button', { name: 'Fermer la navigation' })).toBeFocused()
    expect(await geometry()).toEqual(before)
    await page.keyboard.press('Shift+Tab')
    await expect(page.getByLabel('Thème', { exact: true })).toBeFocused()
    await page.getByLabel('Thème', { exact: true }).selectOption('dark')
    await page.screenshot({ path: info.outputPath('navigation-dark.png') })
    await page.keyboard.press('Escape')
    await expect(dialog).toBeHidden()
    await expect(trigger).toBeFocused()
    expect(await geometry()).toEqual(before)
    expect(await node!.evaluate(el => el === document.querySelector('.cm-content'))).toBe(true)
    expect(await page.evaluate(() => window.youtubeTest.players.length)).toBe(playerCount)
    expect(await page.evaluate(() => window.youtubeTest.players.at(-1)!.pauseCalls)).toBe(0)
    await editor.focus()
    await page.keyboard.type('Remplacement')
    await editor.press('Control+z')
    await expect(editor).toHaveText('Texte conservé')
    await trigger.click()
    await page.mouse.click(width - 24, 100)
    await expect(dialog).toBeHidden()
    await expect(trigger).toBeFocused()
  })
}

test('navigation fermée avant le dialogue de sauvegarde, puis accessible sur toutes les pages', async ({ page, request }) => {
  const video = await (await request.post('/api/v1/videos', { data: { url: 'https://youtu.be/trNavBlock1' } })).json()
  await page.goto('/videos/' + video.id)
  await page.getByRole('textbox', { name: 'Note Markdown' }).fill('Non confirmé')
  await page.route('**/note', route => route.request().method() === 'PUT'
    ? route.fulfill({ status: 400, json: { error: { code: 'bad_request' } } })
    : route.continue())
  await page.getByRole('button', { name: 'Ouvrir la navigation' }).click()
  await page.getByRole('navigation', { name: 'Navigation principale' }).getByRole('link', { name: 'Bibliothèque' }).click()
  await expect(page.getByRole('dialog', { name: 'Navigation', exact: true })).toBeHidden()
  const guard = page.getByRole('dialog', { name: 'Quitter la note ?' })
  await expect(guard).toBeVisible()
  await expect(page.locator('dialog[open]')).toHaveCount(1)
  await guard.getByRole('button', { name: 'Rester sur la note' }).click()
  await page.getByRole('button', { name: 'Ouvrir la navigation' }).click()
  await page.getByRole('navigation').getByRole('link', { name: 'Ajouter une vidéo' }).click()
  await guard.getByRole('button', { name: 'Quitter malgré le risque' }).click()
  await expect(page).toHaveURL('/videos/new')
  await expect(page.getByRole('button', { name: 'Ouvrir la navigation' })).toHaveAttribute('aria-expanded', 'false')
  await page.getByRole('button', { name: 'Ouvrir la navigation' }).click()
  await page.getByRole('navigation').getByRole('link', { name: 'Bibliothèque' }).click()
  await expect(page).toHaveURL('/')
  await expect(page.getByRole('button', { name: 'Ouvrir la navigation' })).toBeVisible()
})
