import { test, expect } from './fixtures'
import { selectTheme } from './navigationHelpers'

for (const width of [320, 375, 1440]) {
  test(`barre de note à ${width} px : noms, clavier, thèmes et infobulles sans débordement`, async ({ page, request }, info) => {
    const video = await (await request.post('/api/v1/videos', { data: { url: `https://youtu.be/trtb${String(width).padStart(7, '0')}` } })).json()
    await page.setViewportSize({ width, height: 1000 })
    await page.goto(`/videos/${video.id}`)
    const editor = page.getByRole('textbox', { name: 'Note Markdown' })
    await expect(editor).toBeVisible()
    const modes = page.getByRole('group', { name: 'Mode de la note', exact: true })
    const editing = modes.getByRole('button', { name: 'Édition', exact: true })
    const reading = modes.getByRole('button', { name: 'Lecture', exact: true })
    const time = page.getByRole('button', { name: 'Insérer le temps actuel', exact: true })
    const capture = page.getByRole('button', { name: 'Capturer une image de la vidéo', exact: true })
    const save = page.getByRole('button', { name: 'Enregistrer la note', exact: true })
    await expect(modes.getByRole('button')).toHaveCount(2)
    await expect(editing).toHaveAttribute('aria-pressed', 'true')
    await expect(reading).toHaveAttribute('aria-pressed', 'false')
    const boxes = await Promise.all([time, capture, save, editing, reading].map(button => button.boundingBox()))
    for (const box of boxes) {
      expect(box!.width).toBe(40)
      expect(box!.height).toBe(40)
      expect(box!.y).toBe(boxes[0]!.y)
    }
    expect(boxes[1]!.x - boxes[0]!.x).toBe(44)
    expect(boxes[2]!.x - boxes[1]!.x - 40).toBeGreaterThanOrEqual(12)
    expect(boxes[3]!.x - boxes[2]!.x - 40).toBe(9)
    expect(boxes[4]!.x - boxes[3]!.x).toBe(40)
    await expect(modes).toHaveCSS('height', '42px')
    await expect(modes).toHaveCSS('padding', '0px')
    await expect(modes).toHaveCSS('border-top-width', '1px')
    await expect(page.locator('.note-controls')).toHaveCSS('padding', '6px 16px')
    const playerModes = page.getByRole('group', { name: 'Mode de lecture', exact: true })
    await expect(playerModes).toHaveCSS('height', '46px')
    await expect(playerModes).toHaveCSS('padding', '2px')
    const youtube = playerModes.getByRole('button', { name: 'YouTube', exact: true })
    await expect(youtube).toHaveCSS('padding-inline', width === 320 ? '4px' : '10px')
    for (const theme of ['light', 'dark'] as const) {
      await selectTheme(page, theme)
      await expect(editing).toHaveCSS('box-shadow', 'none')
      await expect(youtube).not.toHaveCSS('box-shadow', 'none')
      expect(await editing.evaluate(el => getComputedStyle(el).backgroundColor))
        .not.toBe(await reading.evaluate(el => getComputedStyle(el).backgroundColor))
      for (const button of [time, capture, save, editing, reading]) {
        await button.hover()
        const tooltip = page.getByRole('tooltip', { name: (await button.getAttribute('aria-label'))!, exact: true })
        // La sauvegarde enrichit son infobulle avec son état : sa description reste accessible.
        const description = page.locator(`[id="${await button.getAttribute('aria-describedby')}"]`)
        await expect(description).toBeVisible()
        if (button !== save) await expect(tooltip).toBeVisible()
        const box = await description.boundingBox()
        expect(box!.x).toBeGreaterThanOrEqual(0)
        expect(box!.x + box!.width).toBeLessThanOrEqual(width)
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
        if (button === time || button === reading) {
          await page.screenshot({ path: info.outputPath(`${theme}-${width}-${button === time ? 'time' : 'reading'}.png`) })
        }
      }
    }
    await page.getByRole('tab', { name: 'Note', exact: true }).hover()
    await time.focus()
    await time.press('Tab')
    await expect(capture).toBeFocused()
    await capture.press('Tab')
    await expect(save).toBeFocused()
    await save.press('Tab')
    await expect(editing).toBeFocused()
    await expect(editing).toHaveCSS('outline-style', 'solid')
    await expect(editing).toHaveCSS('outline-width', '2px')
    await expect(page.getByRole('tooltip', { name: 'Édition', exact: true })).toBeVisible()
    await page.screenshot({ path: info.outputPath(`keyboard-focus-${width}.png`) })
    await editing.press('Escape')
    await expect(page.getByRole('tooltip', { name: 'Édition', exact: true })).toBeHidden()
    await editing.press('Tab')
    await expect(reading).toBeFocused()
    await reading.press('Enter')
    await expect(reading).toHaveAttribute('aria-pressed', 'true')
    await expect(reading).toHaveCSS('box-shadow', 'none')
    await expect(editing).toHaveAttribute('aria-pressed', 'false')
    await expect(time).toBeDisabled()
    await expect(capture).toBeDisabled()
    await reading.press('Shift+Tab')
    await editing.press('Enter')
    await expect(editor).toBeFocused()
    await page.getByRole('tab', { name: 'Informations', exact: true }).click()
    const note = page.getByRole('tab', { name: 'Note', exact: true })
    await note.click()
    await expect(note).toBeFocused()
    await expect(editor).not.toBeFocused()
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await expect(editing).toHaveCSS('transition-duration', '0s')
  })
}

test('note longue : même session, sélection, historique et conteneur défilant sans écriture visuelle', async ({ page, request }, info) => {
  const video = await (await request.post('/api/v1/videos', { data: { url: 'https://youtu.be/trtoolslong' } })).json()
  const noteURL = `/api/v1/videos/${video.id}/note`
  const content = Array.from({ length: 150 }, (_, i) => `Paragraphe ${i} : une note longue pour vérifier le défilement.\n`).join('\n')
  await request.put(noteURL, { data: { content_md: content, expected_revision: 0 } })
  let writes = 0
  page.on('request', req => { if (req.method() === 'PUT' && req.url().endsWith('/note')) writes++ })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(`/videos/${video.id}`)
  const editor = page.getByRole('textbox', { name: 'Note Markdown' })
  await expect(editor).toBeVisible()
  const node = await editor.elementHandle()
  await editor.click()
  await page.keyboard.press('Control+Home')
  await page.keyboard.press('Shift+ArrowRight')
  const selection = await page.evaluate(() => window.getSelection()?.toString())
  const contentArea = page.locator('.note-content')
  const toolbar = page.locator('.note-controls .note-toolbar')
  const toolbarY = (await toolbar.boundingBox())!.y
  await contentArea.evaluate(el => { el.scrollTop = 900 })
  expect(await contentArea.evaluate(el => el.scrollTop)).toBe(900)
  expect((await toolbar.boundingBox())!.y).toBe(toolbarY)
  await page.getByRole('button', { name: 'Lecture', exact: true }).click()
  await expect(page.getByLabel('Lecture de la note')).toBeVisible()
  const readingScroll = await contentArea.evaluate(el => el.scrollTop)
  await page.getByRole('button', { name: 'Édition', exact: true }).click()
  await expect(editor).toBeFocused()
  expect(await page.evaluate(() => window.getSelection()?.toString())).toBe(selection)
  const editingScroll = await contentArea.evaluate(el => el.scrollTop)
  await info.attach('défilement partagé', { body: JSON.stringify({ readingScroll, editingScroll }), contentType: 'application/json' })
  expect(await node!.evaluate(el => el === document.querySelector('.cm-content'))).toBe(true)
  await page.getByRole('tab', { name: 'Informations', exact: true }).click()
  await page.getByRole('tab', { name: 'Note', exact: true }).click()
  expect(await contentArea.evaluate(el => el.scrollTop)).toBe(editingScroll)
  expect(writes).toBe(0)
  await editor.focus()
  await page.keyboard.press('Control+End')
  await page.keyboard.type('suite')
  await page.getByRole('button', { name: 'Lecture', exact: true }).click()
  await page.getByRole('button', { name: 'Édition', exact: true }).click()
  await page.keyboard.press('Control+z')
  await expect(editor).not.toContainText('suite')
  await page.keyboard.press('Control+Shift+Z')
  await expect(editor).toContainText('suite')
})
